import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:focusbro/screens/enhanced_pdf_reader_screen.dart';

void main() {
  test('round-trips PDF bookmark storage as JSON', () {
    final bookmark = PdfBookmark(
      id: 'bookmark-1',
      pageNumber: 4,
      title: 'Important section',
      description: 'Review this',
      createdAt: DateTime.utc(2026, 6, 9),
      category: BookmarkCategory.review,
      color: Colors.green,
      isAutoGenerated: true,
    );

    final restored = PdfBookmark.decodeStored(bookmark.encodeForStorage());

    expect(restored?.id, bookmark.id);
    expect(restored?.pageNumber, bookmark.pageNumber);
    expect(restored?.title, bookmark.title);
    expect(restored?.description, bookmark.description);
    expect(restored?.createdAt, bookmark.createdAt);
    expect(restored?.category, bookmark.category);
    expect(restored?.color.toARGB32(), bookmark.color.toARGB32());
    expect(restored?.isAutoGenerated, isTrue);
  });

  test('migrates legacy pipe-separated PDF bookmarks', () {
    final restored = PdfBookmark.decodeStored(
      'legacy-id|7|Legacy bookmark|null|2026-06-09T00:00:00.000Z|999|'
      '${Colors.blue.toARGB32()}|false',
    );

    expect(restored?.id, 'legacy-id');
    expect(restored?.pageNumber, 7);
    expect(restored?.description, isNull);
    expect(restored?.category, BookmarkCategory.values.last);
  });

  test('ignores invalid stored PDF bookmarks', () {
    expect(PdfBookmark.decodeStored('invalid'), isNull);
  });
}
